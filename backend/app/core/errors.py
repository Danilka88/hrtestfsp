"""Доменные ошибки: единая форма вместо копий в каждом сервисе.

Сервисы бросают свои исключения, а обработчик API (`app/api/errors.py`) сводит их
к HTTP-ответам. Форма у всех одна — код и сообщение, — поэтому различаться должны
только название и смысл: так `raise MarketplaceError(409, "...")` читается как
намерение, а не как повтор кода.

Обработчик регистрируется один раз на базовый класс, поэтому новое исключение
достаточно унаследовать: про «забыл зарегистрировать» помнить не нужно.
"""

from __future__ import annotations


class DomainError(Exception):
    """Ошибка бизнес-правила: несёт HTTP-код и сообщение для клиента."""

    def __init__(self, status_code: int, detail: str) -> None:
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


class BadRequest(DomainError):
    """Ошибка без собственного кода: ответ 400.

    Нужна там, где у ошибки нет разумного варианта кода, кроме 400, — например,
    неудачный разбор загруженного резюме.
    """

    def __init__(self, detail: str) -> None:
        super().__init__(400, detail)
